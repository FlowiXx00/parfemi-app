"use client";

import { useState } from "react";
import { PiCheck, PiCopy, PiQrCode } from "react-icons/pi";
import type { IpsPaymentView } from "@/features/orders/lib/ips-qr";
import { formatRsd } from "@/lib/format";
import styles from "./ips-payment-card.module.css";

/** After the order: IPS QR for instant payment + details for a manual transfer (with "copy" buttons). */
export default function IpsPaymentCard({ payment }: { payment: IpsPaymentView }) {
  const [copied, setCopied] = useState<string | null>(null);

  function copy(key: string, value: string) {
    void navigator.clipboard?.writeText(value).then(() => {
      setCopied(key);
      window.setTimeout(() => setCopied((current) => (current === key ? null : current)), 1600);
    });
  }

  const reference = payment.reference ? `${payment.reference.slice(0, 2)} ${payment.reference.slice(2)}` : null;
  const rows: { key: string; label: string; value: string; copyValue?: string }[] = [
    { key: "payee", label: "Primalac", value: payment.payeeName },
    { key: "account", label: "Račun", value: payment.account, copyValue: payment.account.replace(/-/g, "") },
    { key: "amount", label: "Iznos", value: formatRsd(payment.amountRsd), copyValue: String(payment.amountRsd) },
    { key: "purpose", label: "Svrha", value: payment.purpose },
    ...(reference ? [{ key: "reference", label: "Poziv na broj", value: reference, copyValue: payment.reference ?? "" }] : []),
  ];

  return (
    <section className={styles.card} aria-labelledby="ips-title">
      <div className={styles.head}>
        <span className={styles.icon} aria-hidden="true">
          <PiQrCode />
        </span>
        <div>
          <h3 id="ips-title" className={styles.title}>
            Plati odmah preko IPS QR koda
          </h3>
          <p className={styles.sub}>Ili pouzećem kuriru — kako ti više odgovara.</p>
        </div>
      </div>

      <div className={styles.body}>
        <div className={styles.qrWrap}>
          {/* The SVG is generated by our server (qrcode library), not user input */}
          <div className={styles.qr} dangerouslySetInnerHTML={{ __html: payment.qrSvg }} role="img" aria-label="IPS QR kod za uplatu" />
          <p className={styles.qrHint}>
            Skeniraj u m-banking aplikaciji (<strong>IPS skeniraj</strong>). Na telefonu: sačuvaj screenshot i izaberi
            „Plati sa slike”.
          </p>
        </div>

        <dl className={styles.details}>
          {rows.map((row) => (
            <div key={row.key} className={styles.row}>
              <dt>{row.label}</dt>
              <dd>
                <span>{row.value}</span>
                {row.copyValue !== undefined && (
                  <button
                    type="button"
                    className={styles.copy}
                    onClick={() => copy(row.key, row.copyValue ?? row.value)}
                    aria-label={`Kopiraj: ${row.label}`}
                  >
                    {copied === row.key ? <PiCheck /> : <PiCopy />}
                  </button>
                )}
              </dd>
            </div>
          ))}
        </dl>
      </div>

      <p className={styles.note}>
        Uplata stiže odmah (instant transfer). Porudžbinu šaljemo čim je vidimo — podatke za uplatu imaš i u mejlu.
      </p>
    </section>
  );
}
