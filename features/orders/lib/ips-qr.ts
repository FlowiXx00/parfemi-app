/**
 * NBS IPS QR code ("Prenesi"): the customer scans it in their banking app and pays by instant transfer.
 * Format: K:PR|V:01|C:1|R:<18-digit
 * account>|N:<payee>|I:RSD<amount>|SF:<code>|S:<purpose>|RO:<model+reference>
 * Spec: https://ips.nbs.rs/PDF/Smernice_Generator_Validator_IPS_QR_Kod.pdf
 */

export type IpsQrInput = {
  /** Payee account number in any format ("160-5100100000000-12", "160510010000000012"…) */
  account: string;
  /** Payee name (and city), at most 70 characters */
  payeeName: string;
  amountRsd: number;
  /** Payment code (3 digits); 289 = transactions ordered by individuals */
  paymentCode?: string;
  /** Payment purpose, at most 35 characters */
  purpose: string;
  /** Model + reference number, e.g. "00611992" (no spaces) */
  reference?: string | null;
};

export const DEFAULT_PAYMENT_CODE = "289";

/** Payment details the server returns with the order (shown to the customer + QR). */
export type IpsPaymentView = {
  /** Account formatted for display ("160-0000000051001-12") */
  account: string;
  payeeName: string;
  amountRsd: number;
  purpose: string;
  /** Payment reference (model 00 + digits) */
  reference: string | null;
  paymentCode: string;
  /** Ready QR code as SVG (generated by the server, qrcode library) */
  qrSvg: string;
};

/** "160-51001-12" -> "160000000005100112": bank (3) + account zero-padded to 13 + check digits (2). */
export function normalizeAccount(raw: string): string | null {
  const trimmed = raw.trim();
  if (!trimmed) return null;

  const parts = trimmed.split(/[\s-]+/).filter(Boolean);
  if (parts.length === 3 && parts.every((part) => /^\d+$/.test(part))) {
    const [bank, middle, control] = parts as [string, string, string];
    if (bank.length !== 3 || control.length !== 2 || middle.length > 13) return null;
    return `${bank}${middle.padStart(13, "0")}${control}`;
  }

  const digits = trimmed.replace(/[\s-]/g, "");
  return /^\d{18}$/.test(digits) ? digits : null;
}

/** Account check digits (ISO 7064, MOD 97-10): the whole 18-digit number mod 97 must equal 1. */
export function isValidAccount(account18: string): boolean {
  if (!/^\d{18}$/.test(account18)) return false;
  return BigInt(account18) % BigInt(97) === BigInt(1);
}

/** 3800 -> "RSD3800,00" (comma as the decimal separator, as NBS requires). */
export function formatIpsAmount(amountRsd: number): string {
  const fixed = Math.max(0, amountRsd).toFixed(2).replace(".", ",");
  return `RSD${fixed}`;
}

/** Reference from the order number: model 00 + digits ("AD-611992" -> "00611992"). */
export function referenceFromOrderNumber(orderNumber: string): string | null {
  const digits = orderNumber.replace(/\D/g, "").slice(0, 20);
  return digits ? `00${digits}` : null;
}

/** Strips "|" (the field separator) and trims to the allowed length. */
function clean(value: string, max: number) {
  return value.replace(/\|/g, " ").replace(/\s+/g, " ").trim().slice(0, max);
}

/** The text encoded into the QR. Throws if the account is invalid (so the customer can't pay to a wrong account). */
export function buildIpsQrPayload(input: IpsQrInput): string {
  const account = normalizeAccount(input.account);
  if (!account || !isValidAccount(account)) {
    throw new Error("Neispravan broj računa za IPS QR (proveri IPS_ACCOUNT_NUMBER).");
  }
  if (!(input.amountRsd > 0)) throw new Error("Iznos za IPS QR mora biti veći od nule.");

  const paymentCode = /^\d{3}$/.test(input.paymentCode ?? "") ? input.paymentCode! : DEFAULT_PAYMENT_CODE;
  const fields = [
    "K:PR",
    "V:01",
    "C:1",
    `R:${account}`,
    `N:${clean(input.payeeName, 70)}`,
    `I:${formatIpsAmount(input.amountRsd)}`,
    `SF:${paymentCode}`,
    `S:${clean(input.purpose, 35)}`,
  ];
  if (input.reference && /^\d{2}[\d-]{1,22}$/.test(input.reference)) fields.push(`RO:${input.reference}`);
  return fields.join("|");
}

/** "160000000005100112" -> "160-0000000051001-12" (for display to the customer) */
export function formatAccount(account18: string) {
  return `${account18.slice(0, 3)}-${account18.slice(3, 16)}-${account18.slice(16)}`;
}
